#!/usr/bin/env node
/**
 * Guidance Polish — CSS block extractor.
 *
 * Reads app/globals.css and writes deploy/guidance-polish-final/guidance-polish.css
 * containing ONLY the five scoped Guidance Polish blocks.
 *
 * Blocks are located by their anchor comment (not by hard-coded line numbers) and
 * terminated at the next top-level `/* ` comment or top-level selector that is not
 * part of the block. Every block is verified to be brace-balanced and free of any
 * Counselor OS selector before it is written.
 *
 * Usage:  node deploy/guidance-polish-final/extract-css-blocks.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..");
const source = resolve(repoRoot, "app", "globals.css");
const target = resolve(here, "guidance-polish.css");

/** Anchor = first line of the block. Stop = first line AFTER the block. */
const BLOCKS = [
  {
    id: "A",
    issue: "8 (V1)",
    name: "Journey step footer — shared sizing",
    anchor: "/* Journey step footer",
    stop: "/* ── Right-hand vertical timeline sidebar",
  },
  {
    id: "B",
    issue: "1",
    name: "Persian upload status line",
    anchor: "/* Persian status line so the field never relies",
    stop: ".gp-upload-field__icon {",
  },
  {
    id: "C",
    issue: "3",
    name: "Universities hub — searchable index",
    anchor: "Universities hub — searchable index over the Discover catalog",
    stop: "Discover majors explorer — mobile touch-target polish",
  },
  {
    id: "D",
    issue: "4",
    name: "Discover majors explorer — mobile touch-target polish",
    anchor: "Discover majors explorer — mobile touch-target polish",
    stop: "Discover systems explorer",
  },
  {
    id: "E",
    issue: "2 + 10",
    name: "Yellow guidance dashboard — hierarchy + touch-target polish",
    anchor: "Yellow guidance dashboard — hierarchy + touch-target polish",
    stop: "Counselor OS (cos-*)",
  },
];

/** Selectors that must never leak into the Guidance Polish fragment. */
const FORBIDDEN = [
  /\bcos-/,
  /guidance-counseling/i,
  /counselor/i,
  /BookingAdvisor/i,
];

const lines = readFileSync(source, "utf8").split(/\r?\n/);

function findLine(needle, from = 0) {
  for (let i = from; i < lines.length; i += 1) {
    if (lines[i].includes(needle)) return i;
  }
  return -1;
}

const chunks = [];
let failures = 0;

for (const block of BLOCKS) {
  const start = findLine(block.anchor);
  if (start === -1) {
    console.error(`FAIL  block ${block.id}: anchor not found -> ${block.anchor}`);
    failures += 1;
    continue;
  }
  const stopAt = findLine(block.stop, start + 1);
  if (stopAt === -1) {
    console.error(`FAIL  block ${block.id}: stop marker not found -> ${block.stop}`);
    failures += 1;
    continue;
  }

  // Trim trailing blank lines so the emitted fragment is stable.
  let end = stopAt - 1;
  while (end > start && lines[end].trim() === "") end -= 1;

  const body = lines.slice(start, end + 1);
  const text = body.join("\n");

  const open = (text.match(/\{/g) || []).length;
  const close = (text.match(/\}/g) || []).length;
  if (open !== close) {
    console.error(
      `FAIL  block ${block.id}: unbalanced braces (${open} open / ${close} close)`,
    );
    failures += 1;
    continue;
  }

  const dirty = FORBIDDEN.filter((rx) => rx.test(text));
  if (dirty.length > 0) {
    console.error(
      `FAIL  block ${block.id}: Counselor OS selector leaked -> ${dirty.join(", ")}`,
    );
    failures += 1;
    continue;
  }

  console.log(
    `OK    block ${block.id} (issue ${block.issue}) lines ${start + 1}-${end + 1} ` +
      `(${body.length} lines, ${open} rules) — ${block.name}`,
  );

  chunks.push(
    [
      `/* ===== GUIDANCE-POLISH BLOCK ${block.id} — issue ${block.issue} — ${block.name} ===== */`,
      text,
      `/* ===== END GUIDANCE-POLISH BLOCK ${block.id} ===== */`,
    ].join("\n"),
  );
}

if (failures > 0) {
  console.error(`\n${failures} block(s) failed extraction. Nothing was written.`);
  process.exit(1);
}

const header = [
  "/* ==========================================================================",
  "   SetareganPlus — Guidance Polish scoped CSS fragment",
  "   Generated by deploy/guidance-polish-final/extract-css-blocks.mjs",
  "",
  "   APPEND ONLY. Never replace app/globals.css with this file.",
  "   Every block is additive and must stay AFTER the existing base rules for",
  "   .gpj-actions*, .gp-upload-field*, .guidance-command-* and the Discover",
  "   explorers, which is why end-of-file is the correct insertion point.",
  "",
  "   Verified at generation time to contain none of the out-of-scope selector",
  "   families that this deployment must not ship.",
  "   ========================================================================== */",
  "",
].join("\n");

writeFileSync(target, `${header}${chunks.join("\n\n")}\n`, "utf8");
console.log(`\nWrote ${target}`);
