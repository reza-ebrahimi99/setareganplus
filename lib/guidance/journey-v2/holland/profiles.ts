/** Same intensity bands as student Holland result UI. */
export function hollandScoreIntensity(value: number): string {
  if (value >= 75) return "بسیار پررنگ";
  if (value >= 60) return "پررنگ";
  if (value >= 45) return "متوسط";
  if (value >= 30) return "کم‌رنگ";
  return "بسیار کم‌رنگ";
}

export function isHollandType(value: string): value is HollandType {
  return (HOLLAND_TYPES as readonly string[]).includes(value);
}
